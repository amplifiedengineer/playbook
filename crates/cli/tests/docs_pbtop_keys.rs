//! The key table in `docs/pbtop.md` is generated from the same list the help
//! window shows (`playbook::usage::tui::keys::help_lines()`), so the page
//! cannot name a key that does not exist or miss one that does. The table sits
//! between two marker comments. This test rebuilds it and fails when the page
//! differs.
//!
//! Regenerate with: `UPDATE_REFERENCE=1 cargo test -p playbook --test docs_pbtop_keys`

use playbook::usage::tui::keys::{help_lines, HelpLine};
use std::fs;
use std::path::PathBuf;

const PAGE: &str = "docs/pbtop.md";
const START: &str = "<!-- keys:start -->";
const END: &str = "<!-- keys:end -->";
const REGEN: &str = "UPDATE_REFERENCE=1 cargo test -p playbook --test docs_pbtop_keys";

fn root() -> PathBuf {
    PathBuf::from(env!("PLAYBOOK_REPO_ROOT"))
}

/// The keys of one binding as code spans: `Down, j` becomes `` `Down`, `j` ``.
/// A name with spaces, such as `1 to 6`, stays one span.
fn key_cell(shown: &str) -> String {
    shown
        .split(", ")
        .map(|key| format!("`{key}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// A table cell with `|` escaped.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// The generated block, markers included, for the given help lines.
fn block(lines: &[HelpLine]) -> String {
    let mut out = String::new();
    out.push_str(START);
    out.push('\n');
    out.push_str(&format!(
        "<!-- Generated by crates/cli/tests/docs_pbtop_keys.rs from the help window. Do not edit by hand.\nRegenerate with: {REGEN} -->\n"
    ));
    let mut open = false;
    for line in lines {
        match line {
            HelpLine::Heading(title) => {
                out.push_str(&format!(
                    "\n**{title}**\n\n| Key | What it does | Where |\n|---|---|---|\n"
                ));
                open = true;
            }
            HelpLine::Key {
                shown,
                text,
                panels,
            } if open => {
                out.push_str(&format!(
                    "| {} | {} | {} |\n",
                    key_cell(shown),
                    cell(text),
                    cell(panels)
                ));
            }
            HelpLine::Key { .. } | HelpLine::Blank => {}
        }
    }
    out.push('\n');
    out.push_str(END);
    out
}

/// `page` with the text between the markers replaced by `block`. An error says
/// which marker is missing or out of order.
fn splice(page: &str, block: &str) -> Result<String, String> {
    let start = page
        .find(START)
        .ok_or_else(|| format!("{PAGE} has no {START} marker"))?;
    let end = page
        .find(END)
        .ok_or_else(|| format!("{PAGE} has no {END} marker"))?;
    if end < start {
        return Err(format!("{PAGE} has {END} before {START}"));
    }
    Ok(format!(
        "{}{}{}",
        &page[..start],
        block,
        &page[end + END.len()..]
    ))
}

#[test]
fn the_keys_block_matches_the_help_window() {
    let path = root().join(PAGE);
    let page = fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {PAGE}: {e}"));
    let fresh = splice(&page, &block(&help_lines())).unwrap_or_else(|e| panic!("{e}"));
    if std::env::var_os("UPDATE_REFERENCE").is_some() {
        fs::write(&path, &fresh).unwrap();
        return;
    }
    assert!(
        page == fresh,
        "the keys block in {PAGE} is out of date with the help window.\nRegenerate it with: {REGEN}"
    );
}

#[test]
fn a_missing_end_marker_fails_and_names_it() {
    let err = splice(&format!("text\n{START}\nold\n"), "new").unwrap_err();
    assert!(err.contains(END), "{err}");
}

#[test]
fn a_missing_start_marker_fails_and_names_it() {
    let err = splice(&format!("text\n{END}\n"), "new").unwrap_err();
    assert!(err.contains(START), "{err}");
}

#[test]
fn markers_in_the_wrong_order_fail() {
    let err = splice(&format!("{END}\n{START}\n"), "new").unwrap_err();
    assert!(err.contains("before"), "{err}");
}

#[test]
fn splicing_replaces_only_the_text_between_the_markers() {
    let page = format!("top\n{START}\nold\n{END}\nbottom\n");
    let out = splice(&page, &format!("{START}\nnew\n{END}")).unwrap();
    assert_eq!(out, format!("top\n{START}\nnew\n{END}\nbottom\n"));
}

#[test]
fn every_key_of_the_help_window_is_in_the_block() {
    let text = block(&help_lines());
    let mut keys = 0;
    for line in help_lines() {
        if let HelpLine::Key { shown, .. } = line {
            assert!(text.contains(&key_cell(shown)), "missing {shown}");
            keys += 1;
        }
    }
    assert!(keys > 20, "only {keys} keys");
}

#[test]
fn the_block_and_the_page_name_none_of_the_cut_settings() {
    let page = fs::read_to_string(root().join(PAGE)).unwrap();
    let text = block(&help_lines());
    for key in [
        "usage.refreshSeconds",
        "usage.telemetryRetentionDays",
        "usage.telemetryMaxRows",
        "usage.autoIngest",
        "usage.autoIngestMinutes",
    ] {
        assert!(!text.contains(key), "the generated block names {key}");
        assert!(!page.contains(key), "{PAGE} names {key}");
    }
}

#[test]
fn a_pipe_in_a_cell_is_escaped() {
    assert_eq!(cell("a|b"), "a\\|b");
}
